// Turns the UI source files into one JS module so the Worker can serve them.
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../src/ui/', import.meta.url);
const read = (f) => readFileSync(new URL(f, dir), 'utf8');
const css = read('portal.css'), js = read('portal-client.js'), admin = read('admin.html');
// Portal pages are rendered as Liquid by Shopify: the shared CSS/JS must not contain Liquid delimiters.
for (const [name, s] of [['portal.css', css], ['portal-client.js', js]]) {
  if (/\{\{|\{%/.test(s)) throw new Error(name + ' contains "{{" or "{%", which Liquid would try to render.');
}
const min = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\n\s+/g, '\n');
writeFileSync(new URL('generated.mjs', dir),
  '// AUTO-GENERATED by scripts/build-ui.mjs. Edit the files in src/ui/ instead.\n' +
  `export const PORTAL_CSS = ${JSON.stringify(min(css))};\n` +
  `export const PORTAL_JS = ${JSON.stringify(js)};\n` +
  `export const ADMIN_HTML = ${JSON.stringify(admin)};\n`);
console.log('ui built');
